// Turns content/questions.json into supabase/seed/questions.sql. Safe to re-run: existing
// questions are updated, nothing is removed, and children's history is never touched.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const bank = JSON.parse(readFileSync(join(root, 'content/questions.json'), 'utf8'));
const lit = (s) => `'${String(s).replaceAll("'", "''")}'`;

const lines = ['-- Generated by scripts/seed-questions.mjs from content/questions.json. Do not edit by hand.'];
for (let i = 0; i < bank.length; i += 40) {
  const chunk = bank.slice(i, i + 40);
  lines.push(
    'insert into public.questions (id, subject, grade, skill, difficulty, prompt, choices) values',
    chunk.map((q) => `  (${lit(q.id)}, ${lit(q.subject)}, ${q.grade}, ${lit(q.skill)}, ${q.difficulty}, ${lit(q.prompt)}, ${lit(JSON.stringify(q.choices))}::jsonb)`).join(',\n'),
    'on conflict (id) do update set subject = excluded.subject, grade = excluded.grade, skill = excluded.skill,',
    '  difficulty = excluded.difficulty, prompt = excluded.prompt, choices = excluded.choices;',
    'insert into public.question_keys (question_id, answer, explanation) values',
    chunk.map((q) => `  (${lit(q.id)}, ${q.answer}, ${lit(q.explanation)})`).join(',\n'),
    'on conflict (question_id) do update set answer = excluded.answer, explanation = excluded.explanation;',
  );
}
writeFileSync(join(root, 'supabase/seed/questions.sql'), lines.join('\n') + '\n');
console.log(`wrote ${bank.length} questions`);
